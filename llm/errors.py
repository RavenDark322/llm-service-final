"""Классы ошибок слоя LLM. От класса зависит реакция: ретрай, fallback или исправление конфига."""


class LLMError(Exception):
    """Базовая ошибка взаимодействия с моделью."""


class TransientLLMError(LLMError):
    """Временная ошибка: таймаут, обрыв соединения, HTTP 5xx, 429. Имеет смысл повторить."""


class PermanentLLMError(LLMError):
    """Постоянная ошибка: 400/401/403/404 — неверный ключ, модель, запрос. Повтор не поможет."""


class LLMResponseError(LLMError):
    """Модель ответила, но не по контракту: пустой ответ, невалидный JSON, нет поля answer."""
